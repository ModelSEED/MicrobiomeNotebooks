# ------------------------------------------------------------------------------------------------ task graph
def build_tasks(cfg):
    tasks = {}

    def add(name, kind, cost, deps=(), prio=50, attempts=2, **kw):
        tasks[name] = dict(name=name, kind=kind, cost=cost, deps=list(deps), prio=prio, attempts=attempts, **kw)

    used = sorted({L for S in cfg["samples"].values() for L in S["libs"]})
    for L in used:
        lib = cfg["libraries"][L]
        if lib.get("pilot_qc"):
            add(f"reads:{L}", "reads", 8, prio=25, lib=L, site=lib["site"])
        else:
            add(f"dl:{L}", "dl", 6, prio=40, attempts=3, lib=L, site=lib["site"])
            add(f"reads:{L}", "reads", 16, deps=[f"dl:{L}"], prio=25, lib=L, site=lib["site"])
    for s, S in cfg["samples"].items():
        add(f"asm:{s}", "asm", 2, prio=5, sample=s)
        add(f"idx:{s}", "idx", 16, [f"asm:{s}"], prio=10, sample=s)
        maps = []
        for L in S["libs"]:
            add(f"map:{s}:{L}", "map", 16, [f"idx:{s}", f"reads:{L}"], prio=20, sample=s, lib=L)
            maps.append(f"map:{s}:{L}")
        add(f"depth:{s}", "depth", len(S["libs"]), maps, prio=15, sample=s)
        add(f"metabat2:{s}", "metabat2", 16, [f"depth:{s}"], prio=12, sample=s)
        add(f"maxbin2:{s}", "maxbin2", 16, [f"depth:{s}"], prio=12, sample=s)
        add(f"concoct:{s}", "concoct", 16, maps, prio=12, sample=s)
        add(f"dastool:{s}", "dastool", 16, [f"metabat2:{s}", f"maxbin2:{s}", f"concoct:{s}"], prio=11, sample=s)
        for gset, deps, prio in (("new", [f"dastool:{s}"], 30), ("old", [], 60), ("orig", [], 70)):
            for k in ("checkm2", "gunc", "checkm1"):
                optional = (k == "checkm1") or gset == "orig"
                add(f"{k}:{gset}:{s}", k, 16, deps, prio=prio + (5 if k == "checkm1" else 0), sample=s, set=gset,
                    optional=optional)
        add(f"skani:{s}", "skani", 8, [f"dastool:{s}"], prio=30, sample=s)
    add("decide", "decide", 1, prio=0, attempts=2)
    return tasks


# ------------------------------------------------------------------------------------------------ driver state
class Driver:
    def __init__(self, cfg):
        self.cfg = cfg
        self.root = cfg["root"]
        self.tasks = build_tasks(cfg)
        for d in (".done", ".failed", ".run", ".rc", ".state", "logs/tasks", "scripts/tasks", "tmp", "reads", "qc"):
            os.makedirs(os.path.join(self.root, d), exist_ok=True)
        self.only_kinds = None   # run --only-kinds: launch only these task kinds (pre-run of downloads)
        self.procs = {}          # name -> Popen (our children) ; adopted ones are polled by pid
        self.running = {}        # name -> run record
        self.deadline = datetime.datetime.strptime(cfg["sf2_deadline_utc"], "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=datetime.timezone.utc)

    def p(self, *a):
        return os.path.join(self.root, *a)

    def done(self, n):
        return os.path.exists(self.p(".done", n))

    def failed(self, n):
        return os.path.exists(self.p(".failed", n))

    def attempts(self, n):
        f = self.p(".state", f"{safe(n)}.attempts")
        return int(open(f).read().strip()) if os.path.exists(f) else 0

    def set_attempts(self, n, k):
        with open(self.p(".state", f"{safe(n)}.attempts"), "w") as fh:
            fh.write(str(k))

    def abandoned(self, s):
        f = self.p(".state", f"{s}.abandoned")
        return json.load(open(f)) if os.path.exists(f) else None

    def blocked(self, n, seen=None):
        """A dep (transitively) failed permanently or its sample was abandoned."""
        t = self.tasks[n]
        if t.get("sample") and self.abandoned(t["sample"]):
            return True
        for d in t["deps"]:
            if self.failed(d) or self.blocked(d):
                return True
        return False

    def terminal(self, n):
        return self.done(n) or self.failed(n) or (n not in self.running and self.blocked(n))

    # ---------------------------------------------------------------- assembly gates
    def check_gates(self):
        for s, S in self.cfg["samples"].items():
            if self.done(f"asm:{s}") or self.abandoned(s):
                continue
            if os.path.exists(S["asm_marker"]) and os.path.exists(S["asm_fasta"]):
                continue
            if os.path.exists(S["asm_marker"]):
                self.abandon(s, "asm_failed", f"done marker {S['asm_marker']} exists but {S['asm_fasta']} does not")
                continue
            if utcnow() > self.deadline:
                self.abandon(s, "asm_timeout", f"no done marker {S['asm_marker']} by {self.cfg['sf2_deadline_utc']}")
                continue
            alive = [p for p in S.get("asm_pids", []) if pid_alive(p["pid"], p.get("needle"))]
            dead_f = self.p(".state", f"{s}.asm_pids_dead_since")
            if S.get("asm_pids") and not alive:
                if not os.path.exists(dead_f):
                    with open(dead_f, "w") as fh:
                        fh.write(ts())
                    log(f"{s}: assembly processes {[p['pid'] for p in S['asm_pids']]} are gone and no done marker yet")
                else:
                    since = datetime.datetime.strptime(open(dead_f).read().strip(), "%Y-%m-%dT%H:%M:%SZ").replace(
                        tzinfo=datetime.timezone.utc)
                    if (utcnow() - since).total_seconds() > 900 and not os.path.exists(S["asm_marker"]):
                        self.abandon(s, "asm_failed", "assembly processes exited 15 min ago without the done marker")
            elif os.path.exists(dead_f):
                os.remove(dead_f)

    def abandon(self, s, state, reason):
        with open(self.p(".state", f"{s}.abandoned"), "w") as fh:
            json.dump({"state": state, "reason": reason, "utc": ts()}, fh, indent=1)
        log(f"{s}: ABANDONED ({state}): {reason}")

    def gate_ok(self, t):
        if t["kind"] == "asm":
            S = self.cfg["samples"][t["sample"]]
            return os.path.exists(S["asm_marker"]) and os.path.exists(S["asm_fasta"]) and not self.abandoned(t["sample"])
        if t["kind"] == "gunc":       # reference data fetched by setup_envs.sh / fetch_gunc_db.sh
            return os.path.exists(os.path.join(self.cfg["tools"]["gunc_db_dir"], ".ok"))
        if t["kind"] == "checkm1":
            return os.path.exists(os.path.join(self.cfg["tools"]["checkm1_data"], ".ok")) and \
                os.path.exists(self.cfg["tools"]["checkm1_env_ok"])
        if t["kind"] == "dl":
            st = os.statvfs(self.root)
            return st.f_bavail * st.f_frsize > self.cfg.get("min_free_gb", 400) * 1e9
        return True

    # ---------------------------------------------------------------- sample states
    def sample_state(self, s):
        ab = self.abandoned(s)
        if ab:
            return ab["state"], ab
        names = [n for n, t in self.tasks.items() if t.get("sample") == s]
        if not all(self.terminal(n) for n in names):
            return "running", None
        hard = [n for n in names if not self.done(n) and not self.tasks[n].get("optional")]
        soft = [n for n in names if not self.done(n) and self.tasks[n].get("optional")]
        if hard:
            return "incomplete", {"failed_or_blocked": hard, "optional_failed": soft}
        return "complete", {"optional_failed": soft}

    def decide_ready(self):
        return all(self.sample_state(s)[0] != "running" for s in self.cfg["samples"])

    # ---------------------------------------------------------------- run / reap
    def launch(self, t):
        n = t["name"]
        k = self.attempts(n) + 1
        self.set_attempts(n, k)
        script = self.p("scripts", "tasks", f"{safe(n)}.{k}.sh")
        with open(script, "w") as fh:
            fh.write(header(self.cfg, t, k) + body(self.cfg, t) + FOOTER)
        logf = self.p("logs", "tasks", f"{safe(n)}.{k}.log")
        rc = self.p(".rc", f"{safe(n)}.{k}")
        for f in (rc,):
            if os.path.exists(f):
                os.remove(f)
        with open(logf, "w") as lf:
            pr = subprocess.Popen(["bash", "-c", 'bash "$1"; echo $? > "$2"', "_", script, rc],
                                  stdout=lf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                                  start_new_session=True, cwd=self.root)
        rec = {"name": n, "attempt": k, "pid": pr.pid, "script": script, "rc": rc, "log": logf, "start": ts(),
               "cost": t["cost"]}
        with open(self.p(".run", f"{safe(n)}.json"), "w") as fh:
            json.dump(rec, fh, indent=1)
        self.procs[n] = pr
        self.running[n] = rec
        log(f"start {n} (attempt {k}, {t['cost']} threads, pid {pr.pid}) -> {logf}")

    def adopt(self):
        for fn in os.listdir(self.p(".run")):
            try:
                rec = json.load(open(self.p(".run", fn)))
            except (OSError, ValueError) as e:
                log(f"unreadable run record {fn}: {e}")
                continue
            n = rec["name"]
            if n not in self.tasks or self.done(n) or self.failed(n):
                continue
            if os.path.exists(rec["rc"]) or pid_alive(rec["pid"], rec["script"]):
                self.running[n] = rec
                log(f"adopted {n} (attempt {rec['attempt']}, pid {rec['pid']})")
            else:
                log(f"{n}: attempt {rec['attempt']} (pid {rec['pid']}) died without an exit code")
                self.finish(n, rec, None)

    def finish(self, n, rec, code):
        t = self.tasks[n]
        rf = self.p(".run", f"{safe(n)}.json")
        if os.path.exists(rf):
            os.remove(rf)
        self.running.pop(n, None)
        self.procs.pop(n, None)
        if code == 0:
            with open(self.p(".done", n), "w") as fh:
                fh.write(f"{ts()} attempt {rec['attempt']} log {rec['log']}\n")
            log(f"done  {n} (attempt {rec['attempt']})")
            return
        k = self.attempts(n)
        if k >= t["attempts"]:
            with open(self.p(".failed", n), "w") as fh:
                fh.write(f"{ts()} exit {code} after {k} attempts; last log {rec['log']}\n")
            log(f"FAILED {n} permanently (exit {code}, {k} attempts; {rec['log']})")
        else:
            with open(self.p(".state", f"{safe(n)}.lastfail"), "w") as fh:
                fh.write(str(time.time()))
            log(f"failed {n} attempt {k} (exit {code}); will retry in >= {RETRY_WAIT} s ({rec['log']})")

    def reap(self):
        for n, rec in list(self.running.items()):
            pr = self.procs.get(n)
            if pr is not None:
                pr.poll()
            if os.path.exists(rec["rc"]):
                try:
                    txt = open(rec["rc"]).read().strip()
                except OSError:
                    continue
                if not txt:                  # written but not yet visible (NFS): look again next cycle
                    rec["empty_rc"] = rec.get("empty_rc", 0) + 1
                    if rec["empty_rc"] < 15:
                        continue
                try:
                    code = int(txt or "1")
                except ValueError:
                    code = 1
                if pr is not None:
                    pr.wait()
                self.finish(n, rec, code)
            elif not pid_alive(rec["pid"]) or (pr is not None and pr.returncode is not None):
                time.sleep(2)
                if not os.path.exists(rec["rc"]):
                    self.finish(n, rec, None)

    def threads_used(self):
        return sum(r["cost"] for r in self.running.values())

    def bg_threads(self):
        bp = self.cfg.get("background_prio", 60)
        return sum(r["cost"] for n, r in self.running.items() if self.tasks[n]["prio"] >= bp)

    def ready(self):
        out = []
        for n, t in self.tasks.items():
            if n == "decide" or n in self.running or self.done(n) or self.failed(n) or self.blocked(n):
                continue
            if not all(self.done(d) for d in t["deps"]):
                continue
            if not self.gate_ok(t):
                continue
            lf = self.p(".state", f"{safe(n)}.lastfail")
            if os.path.exists(lf) and time.time() - float(open(lf).read().strip() or 0) < RETRY_WAIT:
                continue
            out.append(t)
        return sorted(out, key=lambda t: (t["prio"], t["name"]))

    def write_state(self, note=""):
        st = {"utc": ts(), "driver_pid": os.getpid(), "note": note, "threads_used": self.threads_used(),
              "thread_cap": self.cfg["thread_cap"], "sf2_deadline_utc": self.cfg["sf2_deadline_utc"],
              "samples": {}, "running": sorted(self.running), "tasks": {}}
        for s in self.cfg["samples"]:
            state, info = self.sample_state(s)
            st["samples"][s] = {"state": state, "info": info}
        for n in self.tasks:
            st["tasks"][n] = ("done" if self.done(n) else "failed" if self.failed(n) else "running" if n in self.running
                              else "blocked" if self.blocked(n) else "waiting")
        tmp = self.p("STATE.json.part")
        with open(tmp, "w") as fh:
            json.dump(st, fh, indent=1)
        os.replace(tmp, self.p("STATE.json"))
        return st

    def loop(self):
        with open(self.p("driver.pid"), "w") as fh:
            fh.write(str(os.getpid()))
        log(f"driver start: pid {os.getpid()}, root {self.root}, cap {self.cfg['thread_cap']} threads, "
            f"SF2 deadline {self.cfg['sf2_deadline_utc']}")
        self.adopt()
        while True:
            try:
                if self.cycle():
                    return
            except Exception:                # an NFS hiccup must not kill an unattended run
                log("cycle error (continuing):\n" + traceback.format_exc())
            time.sleep(POLL)

    def cycle(self):
        """One scheduling pass; True when the run is finished."""
        if True:
            self.reap()
            self.check_gates()
            if self.done("decide") or self.failed("decide"):
                if not os.path.exists(self.p("DONE")):
                    self.write_done()
                if not self.running:
                    self.write_state("finished")
                    log("all done; driver exits")
                    return True
            elif not os.path.exists(self.p("STOP")):
                if "decide" not in self.running and not self.only_kinds and self.decide_ready():
                    self.write_state("deciding")      # decide.py reads STATE.json
                    self.launch(self.tasks["decide"])
                kinds = {}
                for r in self.running.values():
                    kk = self.tasks[r["name"]]["kind"]
                    kinds[kk] = kinds.get(kk, 0) + 1
                for t in self.ready():
                    if self.only_kinds and t["kind"] not in self.only_kinds:
                        continue
                    lim = self.cfg.get("kind_limits", {}).get(t["kind"])
                    if lim is not None and kinds.get(t["kind"], 0) >= lim:
                        continue
                    if self.threads_used() + t["cost"] > self.cfg["thread_cap"]:
                        continue
                    # OLD/original QC (prio >= background_prio) never holds more than background_cap threads, so
                    # the NEW binning chain keeps most of the budget
                    if t["prio"] >= self.cfg.get("background_prio", 60) and \
                            self.bg_threads() + t["cost"] > self.cfg.get("background_cap", 32):
                        continue
                    self.launch(t)
                    kinds[t["kind"]] = kinds.get(t["kind"], 0) + 1
            if self.only_kinds and not self.running and not any(t["kind"] in self.only_kinds for t in self.ready()) \
                    and not any(self.tasks[n]["kind"] in self.only_kinds and not self.terminal(n) for n in self.tasks):
                self.write_state("only-kinds pre-run finished")
                log(f"only-kinds {sorted(self.only_kinds)}: nothing left; driver exits")
                return True
            self.write_state("only-kinds " + ",".join(sorted(self.only_kinds)) if self.only_kinds else "")
            return False

    def write_done(self):
        dec = {}
        try:
            dec = json.load(open(self.p("DECISION.json")))
        except Exception as e:  # decide failed twice: still write a DECISION.json so the waiter is not stuck
            dec = {"decision": "ERROR", "error": f"decide task failed and DECISION.json unreadable: {e}",
                   "generated_utc": ts()}
            with open(self.p("DECISION.json"), "w") as fh:
                json.dump(dec, fh, indent=1)
        with open(self.p("DONE.part"), "w") as fh:
            fh.write(f"{ts()} decision={dec.get('decision')}\n")
        os.replace(self.p("DONE.part"), self.p("DONE"))
        log(f"wrote DONE (decision {dec.get('decision')})")


def load_cfg(path):
    cfg = json.load(open(path))
    cfg["_config_path"] = os.path.abspath(path)
    return cfg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["run", "plan", "run-one"])
    ap.add_argument("--config", required=True)
    ap.add_argument("--task")
    ap.add_argument("--only-kinds", help="comma list: launch only these task kinds (e.g. dl,reads); no decision")
    ap.add_argument("--cap", type=int, help="override thread_cap")
    a = ap.parse_args()
    cfg = load_cfg(a.config)
    if a.cap:
        cfg["thread_cap"] = a.cap
    d = Driver(cfg)
    if a.only_kinds:
        d.only_kinds = set(a.only_kinds.split(","))
    if a.cmd == "plan":
        d.check_gates()
        st = d.write_state("plan")
        for n, t in sorted(d.tasks.items(), key=lambda x: (x[1]["prio"], x[0])):
            print(f"{st['tasks'][n]:8s} {t['cost']:3d} p{t['prio']:<3d} {n}  <- {','.join(t['deps'])[:120]}")
        print(json.dumps(st["samples"], indent=1))
        return
    if a.cmd == "run-one":
        t = d.tasks[a.task]
        k = d.attempts(a.task) + 1
        script = d.p("scripts", "tasks", f"{safe(a.task)}.manual{k}.sh")
        with open(script, "w") as fh:
            fh.write(header(cfg, t, f"manual{k}") + body(cfg, t) + FOOTER)
        rc = subprocess.call(["bash", script], cwd=d.root)
        print(f"rc={rc}  ({script})")
        if rc == 0:
            with open(d.p(".done", a.task), "w") as fh:
                fh.write(f"{ts()} run-one {script}\n")
        sys.exit(rc)
    d.loop()


if __name__ == "__main__":
    main()
