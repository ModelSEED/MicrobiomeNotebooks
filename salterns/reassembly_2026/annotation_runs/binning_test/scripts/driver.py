#!/usr/bin/env python3
"""Salterns binning test driver (poplar): bin the Arm C (merge + Tadpole + default-mode SPAdes) assemblies of R1_A_D1 and
SF2_C_D1 the way the 2026 KBase pipeline binned its metaSPAdes assemblies, score NEW (these bins) and OLD (the 2026
DAS Tool bins of the same unit) with the same tools, and apply the pre-registered decision rule (decide.py).

One process schedules every step as a detached bash task (setsid), with a global thread cap, per-step done markers and
retries. A restarted driver adopts tasks that are still running. Stdlib only; run with the bt_map env's python:

  cd /scratch1/afreiburger/salterns_2026/binning_test
  nohup setsid nice -n 10 /scratch1/afreiburger/salterns_2026/envs/bt_map/bin/python -I scripts/driver.py run \
      --config scripts/config.json >> logs/driver.log 2>&1 < /dev/null &

Other commands:  driver.py plan --config C      (list tasks and their state; starts nothing)
                 driver.py run-one --config C --task NAME   (run one task in the foreground; for tests)

State under <root>: .done/<task>, .failed/<task>, .run/<task>.json, .rc/<task>.<attempt>, .state/<sample>.abandoned,
STATE.json (summary, rewritten every cycle), logs/tasks/<task>.<attempt>.log, scripts/tasks/<task>.<attempt>.sh.
The decision task writes DECISION.json and REPORT.md; the driver then writes the done marker <root>/DONE.
A file <root>/STOP makes the driver start no new task (running ones finish).
"""
