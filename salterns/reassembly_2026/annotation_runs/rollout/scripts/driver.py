def utcnow():
    return datetime.datetime.now(datetime.timezone.utc)


def ts():
    return utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")


def log(msg):
    print(f"[{ts()}] {msg}", flush=True)


def safe(name):
    return name.replace(":", "__")


def pid_alive(pid, needle=None):
    try:
        os.kill(int(pid), 0)
    except (OSError, ValueError, TypeError):
        return False
    if needle:
        try:
            with open(f"/proc/{pid}/cmdline", "rb") as fh:
                return needle.encode() in fh.read()
        except OSError:
            return False
    return True


def oom_in(files):
    for f in files:
        try:
            with open(f, errors="replace") as fh:
                for line in fh:
                    if any(re.search(p, line, re.I) for p in OOM_PATTERNS):
                        return f"{os.path.basename(f)}: {line.strip()[:160]}"
        except OSError:
            pass
    return None


def meminfo_gb(key="MemAvailable"):
    with open("/proc/meminfo") as fh:
        for line in fh:
            if line.startswith(key + ":"):
                return int(line.split()[1]) / 1024 / 1024
    return 0.0


def free_gb(path):
    st = os.statvfs(path)
    return st.f_bavail * st.f_frsize / 1e9


